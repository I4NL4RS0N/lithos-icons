// Regenerates src/concepts/agent.mjs, the index of agent-made icons in src/agent/ (one concept per file).
import { readdirSync, writeFileSync } from 'node:fs';
const files = readdirSync('src/agent').filter((f) => f.endsWith('.mjs')).sort();
const name = (f) => 'c_' + f.replace(/\.mjs$/, '').replace(/[^a-z0-9]/g, '_');
writeFileSync('src/concepts/agent.mjs', `// Generated by scripts/agent-index.mjs — do not edit.\n${files.map((f) => `import ${name(f)} from '../agent/${f}';`).join('\n')}\nexport default [${files.map(name).join(', ')}];\n`);
console.log(`agent index: ${files.length} concepts`);
